const setLanguage = (language) => {
  const safeLanguage = translations[language] ? language : 'en';
  const dictionary = translations[safeLanguage] || {};
  document.documentElement.lang = safeLanguage;
  document.documentElement.dir = safeLanguage === 'he' ? 'rtl' : 'ltr';
  document.title = safeLanguage === 'he' ? 'לוח הבקרה של Baby Buddy' : 'Baby Buddy Dashboard';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    const englishValue = element.dataset.en || element.textContent || '';
    element.textContent = safeLanguage === 'en' ? englishValue : (dictionary[key] ?? englishValue);
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const key = element.dataset.i18nHtml;
    const englishValue = element.dataset.en || element.innerHTML || '';
    element.innerHTML = safeLanguage === 'en' ? englishValue : (dictionary[key] ?? englishValue);
  });

  document.querySelectorAll('[data-language]').forEach((button) => button.setAttribute('aria-pressed', button.dataset.language === safeLanguage));
  localStorage.setItem('babyBuddyLanguage', safeLanguage);
};

document.querySelectorAll('[data-i18n]').forEach((element) => element.dataset.en = element.textContent);
document.querySelectorAll('[data-i18n-html]').forEach((element) => element.dataset.en = element.innerHTML);
document.querySelectorAll('[data-language]').forEach((button) => button.addEventListener('click', () => setLanguage(button.dataset.language)));
setLanguage(localStorage.getItem('babyBuddyLanguage') || 'en');
